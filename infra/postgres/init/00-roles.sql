-- Ensure non-superuser application role bina_app exists with NOBYPASSRLS
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'bina_app') THEN
    CREATE ROLE bina_app
      LOGIN
      PASSWORD 'bina_app_dev'
      NOSUPERUSER
      NOCREATEDB
      NOCREATEROLE
      NOINHERIT
      NOREPLICATION
      NOBYPASSRLS;
  ELSE
    ALTER ROLE bina_app
      WITH LOGIN PASSWORD 'bina_app_dev'
      NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;
  END IF;
END
$$;

GRANT CONNECT ON DATABASE bina_dev TO bina_app;
GRANT USAGE ON SCHEMA public TO bina_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO bina_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO bina_app;

ALTER DEFAULT PRIVILEGES IN SCHEMA public
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO bina_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public
  GRANT USAGE, SELECT ON SEQUENCES TO bina_app;
